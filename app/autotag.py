"""按商品名自动打标签。

老板录商品时只想填名字和价格，不愿意理解「标签」是什么。但没有标签，
顾客说「来点冰的」「给小孩买点零食」时就推荐不出这件商品——商品等于是
录进去了、卖不出去。

所以这里按名字里的关键词自动推断。宁可多打几个（软标签只影响排序，
打多了不会把别的商品过滤掉），也不要漏打。人群标签（child/adult）
不从名字推——「儿童牛奶」这种名字太少，靠猜容易错。
"""

from __future__ import annotations

# 关键词 -> 标签。按顺序全部跑一遍，命中即累加（一个商品可以有多组标签）。
RULES: list[tuple[tuple[str, ...], tuple[str, ...]]] = [
    (("冰淇淋", "冰淇凌", "冰激凌", "冰激淋", "雪糕", "冰棍", "冰棒", "甜筒", "雪丽糍"),
     ("summer", "sweet")),
    (("可乐", "雪碧", "汽水", "芬达", "七喜", "苏打"), ("summer",)),
    (("矿泉水", "纯净水", "苏打水", "农夫山泉", "怡宝"), ("all",)),
    (("冰红茶", "绿茶", "红茶", "奶茶", "果汁", "饮料", "茶π"), ("summer",)),
    (("啤酒", "二锅头", "白酒", "黄酒", "梅酒", "米酒"), ("drink",)),
    (("牛奶", "酸奶", "豆奶", "早餐奶", "麦片"), ("breakfast",)),
    (("辣条", "鸭脖", "麻辣", "辣", "泡椒", "鸭爪", "凤爪", "牛肉干"), ("spicy",)),
    (("糖", "巧克力", "果冻", "棒棒糖", "软糖", "奶糖", "棉花糖"), ("sweet",)),
    (("薯片", "饼干", "锅巴", "膨化", "虾条", "薯条", "威化"), ("salty", "snack")),
    (("瓜子", "花生", "豆干", "卤蛋", "蚕豆", "肉脯", "烤肠"), ("drink", "salty")),
    (("方便面", "泡面", "面包", "蛋糕", "饼干"), ("snack",)),
    (("口香糖", "薄荷糖"), ("sweet",)),
]


def infer(name: str) -> list[str]:
    """从商品名推断标签。推不出来时返回空列表，由调用方给默认值。"""
    n = (name or "").strip()
    if not n:
        return []
    tags: list[str] = []
    for keywords, tag_list in RULES:
        if any(k in n for k in keywords):
            for t in tag_list:
                if t not in tags:
                    tags.append(t)
    return tags
